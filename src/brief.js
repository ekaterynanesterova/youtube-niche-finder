    if (r.effort) {
      w(`- **Трудозатраты:** ${r.effort.hoursPerWeek} ч готового видео в неделю`
        + `, около ${r.effort.hoursPerMonth} ч в месяц`
        + (r.effort.minutes ? `; типовой ролик — ${r.effort.minutes} мин` : '') + '.');
    }
    const facts = [];
