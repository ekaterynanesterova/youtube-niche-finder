// Бриф — та же собранная статистика, но в виде одного файла, который можно
// целиком отдать в другой чат. Сайт для этого не годится: он читается глазами,
// половина цифр в нём появляется только по клику, а ссылку на GitHub Pages
// модель в чужом чате не всегда может открыть. Сырые данные тоже не годятся —
// videos.json весит тридцать мегабайт.
//
// Поэтому здесь: выводы, конкуренты, живые заголовки, пороги и правила —
// всё, что нужно, чтобы разговор о контент-плане начался не с нуля.

const MARKET = { de: 'немецкий', en: 'английский' };

const num = (n) => (n == null ? '—' : Math.round(n).toLocaleString('ru-RU'));
const pct = (n) => (n == null ? '—' : Math.round(n * 100) + '%');
const usd = (n) => (n == null ? '—' : '$' + Math.round(n).toLocaleString('ru-RU'));

function plural(n, a, b, c) {
  const m = n % 100, k = n % 10;
  return n + ' ' + (m > 10 && m < 20 ? c : k === 1 ? a : k > 1 && k < 5 ? b : c);
}

function berlin(iso) {
  return new Date(iso).toLocaleString('ru-RU', {
    timeZone: 'Europe/Berlin', day: 'numeric', month: 'long', hour: '2-digit', minute: '2-digit',
  });
}

export function renderBrief(P) {
  const T = P.thresholds ?? {};
  const rows = P.verdict ?? [];
  const lead = rows[0];
  const out = [];
  const w = (...s) => out.push(...s);

  w('# Бриф для контент-плана');
  w('');
  w(`Срез на ${berlin(P.computedAt)} по Берлину. Файл собирается заново на каждом прогоне —`,
    'править его руками бессмысленно, правки затрёт следующий сбор.');
  w('');
  w('- Живая версия со всеми кликами: https://ekaterynanesterova.github.io/youtube-niche-finder/');
  w('- Этот файл: https://raw.githubusercontent.com/ekaterynanesterova/youtube-niche-finder/main/docs/brief.md');
  w('');

  w('## Прочитай это первым, если разговор начался с нуля');
  w('');
  w('Задача: запустить faceless-документальный канал на YouTube и вывести его',
    `на ${usd(T.targetMonthlyUsd)} в месяц. Ниша выбирается не на вкус, а по собранным цифрам —`,
    'их и содержит этот файл. Ниже: какие темы сейчас пускают новичков, кто там уже сидит,',
    'какие заголовки сработали и какие ограничения по контенту приняты и не пересматриваются.');
  w('');
  w('**Ограничения, которые уже приняты:**');
  w('');
  w('1. Только длинные видео, от восьми минут. Shorts не рассматриваем.');
  w('2. Не берём темы, где спорят о трактовке, а не о фактах: Вторая мировая, Гитлер, нацизм,',
    'Сталин, геноциды. Это решение принято, обсуждать заново не нужно.');
  w('3. Не делаем AI-конвейер: ни озвучки-роботы поверх стоковой нарезки, ни генерация пачками.',
    'Графика — код и After Effects плюс лицензионный сток.');
  w('4. Основной рынок — английский, немецкий держим как контроль. Причина в цифрах ниже,',
    'в разделе про рынки.');
  w('');

  w('## Насколько этим цифрам можно верить');
  w('');
  w(`- В базе ${num(P.dbSize?.channels)} каналов и ${num(P.dbSize?.videos)} видео.`);
  w(`- Дней накопления: **${P.snapshotDays}**. Всё, что считается по приросту между срезами`,
    '(старым роликам достаётся, живая полка), при малом числе дней шумит.');
  w(`- Тем изучено ${P.seedsDone} из ${P.seedsTotal}. Непройденные темы могут переставить рейтинг.`);
  w('- Инструмент видит только заголовки, длительность, даты и счётчики. Он **не видит содержимое ролика**:',
    'ни картинку, ни монтаж, ни то, сделано это руками или нагенерировано. Последнее слово — за глазами.');
  w(`- Деньги — оценка по единой ставке $${T.rpmUsd} за тысячу просмотров. Настоящая ставка отличается`,
    'по темам в разы и через API недоступна. Это порядок величины, а не обещание дохода.');
  w('');

  w('## Как читать метрики');
  w('');
  w('| Метрика | Что это |');
  w('|---|---|');
  w(`| Свежий ролик у новичка | Медиана просмотров роликов возрастом от ${T.freshMinAgeDays} до ${T.freshMaxAgeDays} дней на каналах моложе года. Главное число: столько соберёт видео, выложенное завтра. |`);
  w(`| Свежих берут ${num(T.workingViews)}+ | Какая доля этих роликов перевалила за ${num(T.workingViews)} просмотров. Повторяемость: медиана может быть приличной, а половина роликов уходить в пустоту. |`);
  w(`| Молодой канал | Каналу меньше ${T.youngChannelDays} дней от первой загрузки (не от регистрации: аккаунт могли завести годами раньше и держать пустым). |`);
  w(`| Новичков зарабатывают | Сколько каналов моложе года вышли хотя бы на ${usd(T.startingUsd)} в месяц. Судить двухмесячный канал целью в ${usd(T.targetMonthlyUsd)} бессмысленно — у него десять роликов. |`);
  w('| Старым достаётся | Доля новых просмотров за сутки, уходящая роликам старше полугода, против их доли в каталоге. Первое больше второго — ролик работает годами. Меньше — беговая дорожка. |');
  w(`| Конвейер | Доля каналов, выпускающих больше ${Math.round((T.conveyorMinutesPerWeek ?? 900) / 60)} часов готового видео в неделю. Мера потока, не качества. |`);
  w('| Роликов по теме на YouTube | Оценка самого YouTube по запросу. Единственная прямая мера размера темы — в отличие от числа каналов, которое показывает лишь то, сколько нашли мы. |');
  w('');

  if (lead) {
    w('## Куда идти');
    w('');
    w(P.headline);
    w('');
    w(`Лидер на сегодня — **${lead.query}**${lead.ru ? ` (${lead.ru})` : ''}, рынок ${lead.market}.`);
    w('');
  }

  w('### Топ ниш');
  w('');
  w('| # | Запрос | Рынок | Свежий ролик | ' + num(T.workingViews)
    + '+ | Новичков зарабатывают | В месяц у новичка | Каналов в теме | Длина ролика |');
  w('|---|---|---|---|---|---|---|---|---|');
  for (const [i, r] of rows.slice(0, 12).entries()) {
    w(`| ${i + 1} | **${r.query}**${r.ru ? `<br><sub>${r.ru}</sub>` : ''} | ${MARKET[r.lang] ?? r.lang} `
      + `| ${num(r.fresh)} | ${pct(r.freshOver20k)} | ${r.young} | ${usd(r.usd)} | ${num(r.nicheChannels)} `
      + `| ${r.minutes == null ? '—' : Math.round(r.minutes) + ' мин'} |`);
  }
  w('');

  w('### Разбор первых ниш');
  w('');
  for (const r of rows.slice(0, 5)) {
    w(`#### ${r.query}${r.ru ? ` — ${r.ru}` : ''} (${MARKET[r.lang] ?? r.lang})`);
    w('');
    w(`- **Почему:** ${r.why}`);
    w(`- **Риск:** ${r.risk}`);
    // effort приходит объектом — на сайте из него верстается строка. Здесь
    // нужен текст, иначе в файл уедет [object Object].
    if (r.effort) {
      w(`- **Трудозатраты:** ${r.effort.hoursPerWeek} ч готового видео в неделю`
        + `, около ${r.effort.hoursPerMonth} ч в месяц`
        + (r.effort.minutes ? `; типовой ролик — ${r.effort.minutes} мин` : '') + '.');
    }
    const facts = [];
    if (r.fastestMonths != null) facts.push(`быстрее всех новичок дошёл за ${Math.round(r.fastestMonths)} мес.`);
    if (r.catalog != null) facts.push(`у дошедших типично ${plural(Math.round(r.catalog), 'ролик', 'ролика', 'роликов')} по теме`);
    if (r.shelf != null) facts.push(`старым роликам достаётся ${pct(r.shelfShare)} новых просмотров при доле каталога ${pct(r.shelfOldShare)}`);
    if (r.totalResults != null) facts.push(`на YouTube по запросу около ${num(r.totalResults)} роликов`);
    if (facts.length) w(`- **Цифры:** ${facts.join('; ')}.`);
    w('');
    const rivals = (r.rivals ?? []).slice(0, 8);
    if (rivals.length) {
      w('Кто уже в теме:');
      w('');
      w('| Канал | Возраст | Подписчиков | В месяц | Свежий ролик | Роликов по теме |');
      w('|---|---|---|---|---|---|');
      for (const c of rivals) {
        w(`| ${c.young ? '🟢 ' : ''}${c.title} | ${c.age == null ? '—' : c.age + ' дн.' + (c.exact ? '' : '?')} `
          + `| ${num(c.subs)} | ${usd(c.usd)} | ${num(c.fresh)} | ${c.inNiche} из ${c.videos} |`);
      }
      w('');
      w('🟢 — канал моложе года. Смотреть надо на них: если зелёных нет, в теме сидят одни старожилы.');
      w('');
    }
    const ex = (P.examples?.[r.id]?.[r.lang] ?? []).slice(0, 6);
    if (ex.length) {
      w('Заголовки, которые сработали у новичков:');
      w('');
      for (const v of ex) {
        w(`- **${v.title}**${v.titleRu ? ` — «${v.titleRu}»` : ''}  `);
        w(`  ${num(v.views)} просмотров · ${v.minutes} мин · канал «${v.channel}» на ${v.channelAge}-й день`
          + (v.earning ? ` · зарабатывает ${usd(v.usd)}/мес` : ''));
      }
      w('');
    }
  }

  const arch = P.archetypes ?? [];
  if (arch.length) {
    w('## Архетипы каналов');
    w('');
    w('Не отдельные темы, а наборы тем, которые дошедшие до денег каналы снимают вместе.',
      'Полезно для контент-плана: показывает, чем заполнять каталог после первых роликов.');
    w('');
    for (const a of arch.slice(0, 5)) {
      w(`- **${a.topics.slice(0, 6).map((t) => t.topic).join(' · ')}**  `);
      w(`  ${plural(a.channels, 'канал', 'канала', 'каналов')}, из них ${a.young} моложе года`
        + (a.fastestDays != null ? `; быстрейший дошёл за ${Math.round(a.fastestDays / 30.4)} мес.` : '')
        + `; типично ${plural(Math.round(a.medianCatalog ?? 0), 'ролик', 'ролика', 'роликов')} и ${usd(a.medianUsd)} в месяц`
        + (a.medianMinutesPerWeek != null ? `; ${(a.medianMinutesPerWeek / 60).toFixed(1)} ч видео в неделю` : ''));
      if (a.examples?.length) w(`  Примеры: ${a.examples.map((e) => e.title).join(', ')}.`);
    }
    w('');
  }

  const mk = P.markets ?? {};
  if (mk.de && mk.en) {
    w('## Рынки: английский против немецкого');
    w('');
    w('| Рынок | Каналов | Моложе года | Из них зарабатывают | Доля |');
    w('|---|---|---|---|---|');
    for (const lang of ['en', 'de']) {
      const m = mk[lang];
      w(`| ${MARKET[lang]} | ${num(m.channels)} | ${num(m.young)} | ${num(m.youngEarning)} | ${pct(m.youngRate)} |`);
    }
    w('');
    w('Разрыв здесь и есть причина делать канал на английском.');
    w('');
  }

  const pend = P.pending ?? [];
  if (pend.length) {
    w('## Ещё изучаем');
    w('');
    w(`Темы, по которым данных мало — меньше ${T.nicheMinChannels} найденных каналов.`,
      'В рейтинг не попадают намеренно: проценты по трём каналам выглядят убедительно и не значат ничего.',
      'Но среди них может оказаться то, что через неделю выйдет в лидеры.');
    w('');
    for (const p of pend.slice(0, 12)) {
      w(`- ${p.query}${p.ru ? ` (${p.ru})` : ''} — ${MARKET[p.lang] ?? p.lang}, `
        + `каналов ${p.channels}, свежий ролик ${num(p.fresh)}`);
    }
    w('');
  }

  return out.join('\n') + '\n';
}
