  w(`| Свежие ролики | Все ролики темы возрастом от ${T.freshMinAgeDays} до ${T.freshMaxAgeDays} дней — по всем каналам, а не только по молодым. Просмотры считаются ВСЕГО за жизнь ролика, а не за сутки. |`);
  w('| Взяли 20k / 100k | Сколько таких роликов перевалило за двадцать и за сто тысяч. Штуками, а не средним: разброс внутри ниши доходит до двадцати пяти раз, и любое одно число его прячет. В «dinosaur documentary» медиана свежего ролика 546 — при том что 55 роликов из 172 взяли двадцать тысяч, а 21 взял сто тысяч. |');
  w('| Лучшее у новичка с нуля | Конкретный ролик: самый успешный свежий ролик канала, который завели незадолго до первой загрузки. Рядом стоит возраст канала и число подписчиков — по ним видно, что это не заслуга накопленной аудитории. |');
  w(`| С нуля взяли ${num(T.workingViews)}+ | Сколько РАЗНЫХ молодых каналов выпустили за эти два месяца хотя бы один ролик выше ${num(T.workingViews)} просмотров. Считаем по каналам, а не по роликам: один канал, заливший тридцать штук, сам себе сделает любой процент. |`);
  w(`| Чистый старт | «Моложе года» меряется от первой загрузки — и четверть таких каналов оказывается воскрешёнными аккаунтами: первый ролик полгода назад, регистрация двенадцать лет назад. У них мог остаться прежний зритель, доказательством «сюда пускают новичка» они не являются. В счёт идут только каналы, у которых между регистрацией и первым роликом прошло не больше ${T.dormantStartDays} дней. |`);
  w(`| Свежих берут ${num(T.workingViews)}+ | Какая доля этих роликов перевалила за ${num(T.workingViews)} просмотров. Повторяемость: медиана может быть приличной, а половина роликов уходить в пустоту. |`);
  w(`| Молодой канал | Каналу меньше ${T.youngChannelDays} дней от первой загрузки, а не от регистрации: аккаунт могли завести годами раньше и держать пустым. Отсюда же оговорка про чистый старт ниже. |`);
  w(`| Новичков зарабатывают | Сколько каналов моложе года вышли хотя бы на ${usd(T.startingUsd)} в месяц. Судить двухмесячный канал целью в ${usd(T.targetMonthlyUsd)} бессмысленно — у него десять роликов. |`);
