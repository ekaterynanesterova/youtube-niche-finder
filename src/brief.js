  w(`| Конвейер | Доля каналов, выпускающих больше ${Math.round((T.conveyorMinutesPerWeek ?? 900) / 60)} часов готового видео в неделю. Мера потока, не качества. |`);
  w('| ⚠ Реклама урезана | Ниша попадает под «спорные темы и деликатные события» YouTube: реклама там ставится не вся или не ставится. Тема разрешена, каналы зарабатывают, но оценка дохода по общей ставке для неё завышена. |');
  w('| Роликов по теме на YouTube | Оценка самого YouTube по запросу. Единственная прямая мера размера темы — в отличие от числа каналов, которое показывает лишь то, сколько нашли мы. |');
